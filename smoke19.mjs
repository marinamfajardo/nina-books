import { chromium } from 'playwright-core';
const [OUT, PHOTO] = process.argv.slice(2);
const BASE = 'http://localhost:4173/nina-books/';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const errors = [];
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'pt-BR' })).newPage();
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(BASE);
await page.click('.bottomnav >> text=Adicionar');
await page.setInputFiles('input[capture]', PHOTO);
await page.click('text=Usar a foto inteira');
await page.fill('form input[required]', 'Guerra Civil');
await page.fill('text=Autor(es) / grupo — separe por vírgula >> xpath=../input', 'Marvel');
await page.click('form button.chip:has-text("Lido")');
await page.click('text=Adicionar à estante');
await page.waitForSelector('.book-hero >> text=Marvel');
await page.click('.bottomnav >> text=Estante');
await page.click('.chip:has-text("Autor / grupo")');
await page.waitForSelector('h1:has-text("Autores / grupos")');
await page.waitForSelector('.group-tile:has-text("Marvel")');
await page.click('.bottomnav >> text=Estatísticas');
await page.click('text=Autores / grupos');
await page.waitForSelector('.list-item:has-text("Marvel")');
await page.click('.list-item:has-text("Marvel")');
await page.waitForSelector('h1:has-text("Marvel")');
await page.screenshot({ path: `${OUT}/v19-marvel.png` });
await browser.close();
console.log(errors.length ? `ERROS: ${errors.join(' | ')}` : 'OK sem erros');
